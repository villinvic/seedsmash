class NormalisedCharacterAttributes:

    def __init__(self, observed: Tuple[str, ...]):
        self.dim = len(observed)
        scales = {
            k: max(data[k] for data in char_data.values())
            for k in observed
        }

        self.data = {
            char: tuple(data[k] / scales[k] for k in observed)
            for char, data in char_data.items()
        }

    def get(self, character: Character) -> Tuple[float, ...]:
      return self.data[character]


